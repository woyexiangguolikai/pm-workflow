"""交互连线清单：**从具体元素出发**，到具体元素或具体页面。

## 为什么起点必须落到元素，而不是页面块

「这页跳到那页」这种页面级连线，开发看完还得自己去找是哪个按钮跳的 —— 而真正要写的
代码恰恰是那个按钮上的事件。所以每条关系的起点都是一个带 `data-el` 的元素，
交互方式与业务说明也挂在元素上，读完一条就知道「改哪个像素点、点下去会怎样」。

## 为什么清单在这里手写，而不是从 prd.json 自动推导

PRD 的 `pageFlow` 是**需求视角**：「BR-101 这条需求有哪些出口」。
连线要的是**界面视角**：「这一屏上哪一个点下去会走到哪里」。
两者不是一一对应 —— 一条 pageFlow 出口可能对应两个入口元素（列表行 + 工单里的同名按钮），
也可能根本没有对应元素（服务端定时任务没有界面）。硬凑会把两边的语义都搞坏。

但**手写必须有约束**，否则会慢慢变成编的。所以：
1. 每条连线必须挂一个**真实存在的需求号**，由 `check-anno.py` 对着 prd.json 校验；
2. `from` 必须是 element-map 里真实存在的元素 id；
3. `to` 若是元素，也必须在 element-map 里存在；若是页面，页面的每条出口都要在 PRD 里能找到出处。

## `to` 的两种写法

| 写法 | 含义 | 连线终点 |
|---|---|---|
| `'a2-tab-account'` | 元素 → 元素 | 落在目标元素的热区上 |
| `'#PG-A3'` | 元素 → 页面 | 落在目标卡片边框的中点 |
| `'#PG-A5/yikatong'` | 元素 → 某页的**某个状态** | 落在该状态卡片边框的中点 |

## 什么关系不画连线

「就地变化」（开关即时生效、输入即校验、展开 FAQ、复制）和「跳出小程序」（客服、电话）
都没有可视落点，画线只会连到空气上。它们进元素清单，标成 `就地` / `外部`，
在说明里写清点了会发生什么。判断标准很简单：**线的另一头有没有东西可以指**。
"""

